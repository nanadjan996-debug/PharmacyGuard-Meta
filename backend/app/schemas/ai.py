"""Pydantic schemas for Meta Muse Spark Open AI Explanation through Baseten."""
from typing import Literal, Optional
from pydantic import BaseModel, Field


class FindingExplanation(BaseModel):
    """Clinical explanation for a specific flagged deterministic finding."""
    rule_identifier: str = Field(..., description="Matches exact deterministic rule identifier")
    category: str = Field(..., description="Echoes deterministic finding category")
    severity: str = Field(..., description="Echoes deterministic finding severity")
    clinical_explanation: str = Field(..., description="Clinical reasoning and patient-specific risk explanation")


class AIExplanationResponse(BaseModel):
    """Structured clinical explanation generated by Meta Muse Spark Open via Baseten."""
    summary: str = Field(..., description="Executive clinical synthesis of findings for the reviewing pharmacist")
    finding_explanations: list[FindingExplanation] = Field(
        default_factory=list,
        description="Detailed explanation for each flagged finding referencing its deterministic rule"
    )
    clinical_context: str = Field(..., description="Synthesis of patient conditions, history, and medication regimen")
    uncertainties: list[str] = Field(
        default_factory=list,
        description="Missing clinical parameters, monitoring labs, or unknowns"
    )
    review_considerations: list[str] = Field(
        default_factory=list,
        description="Actionable clinical points for the human pharmacist to evaluate"
    )
    ai_status: Literal["available", "unavailable", "timeout", "rejected", "disabled"] = Field(
        ..., description="Operational status of the AI explanation generation"
    )
    status_detail: Optional[str] = Field(None, description="Diagnostic detail or failure reason if not available")
    model_name: Optional[str] = Field("meta-models/muse-spark-open", description="Target model identifier")
    disclaimer: str = Field(
        default=(
            "AI-generated explanatory assistance only. Non-authoritative clinical decision support. "
            "Does not approve prescriptions, authorize dispensing, or alter deterministic safety findings."
        ),
        description="Mandatory clinical advisory disclaimer"
    )

